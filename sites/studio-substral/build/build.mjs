#!/usr/bin/env node
/**
 * Builds the Studio Substral dimensional object.
 *
 *   src/dimensional.js  ->  assets/js/dimensional.js
 *
 * three.js is tree-shaken and minified here rather than shipped whole: the
 * scene uses a small part of the library and the performance doctrine (§20)
 * does not allow paying for the rest. The output is committed so the site
 * directory stays directly publishable with no build step at deploy time.
 *
 *   node build.mjs           build and report
 *   node build.mjs --check   verify the committed output matches the source
 */

import { build } from 'esbuild';
import { gzipSync, brotliCompressSync } from 'node:zlib';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(here, '..');
const entry = path.join(site, 'src', 'dimensional.js');
const out = path.join(site, 'assets', 'js', 'dimensional.js');

/** Compressed budget for the deferred dimensional object, in kilobytes. */
const BUDGET_GZIP_KB = 170;

const BANNER = `/* Studio Substral — dimensional object. Generated by build/build.mjs.
 * Do not edit: change src/dimensional.js and rebuild.
 * Bundles three.js (MIT) — see assets/js/dimensional.LICENSE.txt. */`;

async function bundle() {
  const result = await build({
    entryPoints: [entry],
    // The source lives outside this directory, so point the resolver at the
    // build tooling's own dependencies.
    nodePaths: [path.join(here, 'node_modules')],
    bundle: true,
    format: 'esm',
    target: ['es2022'],
    minify: true,
    treeShaking: true,
    legalComments: 'none',
    banner: { js: BANNER },
    write: false,
    logLevel: 'warning',
  });
  return result.outputFiles[0].text;
}

function report(code) {
  const raw = Buffer.byteLength(code);
  const gz = gzipSync(code, { level: 9 }).length;
  const br = brotliCompressSync(code).length;
  const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
  console.log(`  raw    ${kb(raw)}`);
  console.log(`  gzip   ${kb(gz)}`);
  console.log(`  brotli ${kb(br)}`);
  return gz;
}

const check = process.argv.includes('--check');
const code = await bundle();

console.log(`${check ? 'Checking' : 'Building'} dimensional object`);
const gz = report(code);

if (gz > BUDGET_GZIP_KB * 1024) {
  console.error(
    `\nOver budget: ${(gz / 1024).toFixed(1)} KB gzip exceeds ${BUDGET_GZIP_KB} KB.`
  );
  process.exit(1);
}

if (check) {
  const existing = await readFile(out, 'utf8').catch(() => null);
  if (existing !== code) {
    console.error('\nassets/js/dimensional.js is stale. Run: npm run build');
    process.exit(1);
  }
  console.log('\nCommitted bundle matches source.');
} else {
  await writeFile(out, code);
  console.log(`\nWrote ${path.relative(site, out)}`);
}
