'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {Pool}=require('pg');
const {startDisposablePostgres}=require('../../../../test/helpers/disposablePostgres');
const {ConversationContextStore,project}=require('../ConversationContextStore');
test('PostgreSQL: replay migration, restart, tenant isolation, concurrency, expiry, deletion and corrupt recovery', {timeout:60000},async t=>{
  const instance=await startDisposablePostgres('max-context-');
  const db=new Pool({connectionString:instance.connectionString});
  t.after(async()=>{await db.end();await instance.stop();});
  const migration=fs.readFileSync('migrations/2026-11-09-max-conversation-context.sql','utf8');
  await db.query(migration);await db.query(migration);
  let now=Date.now();
  const store=new ConversationContextStore({db,now:()=>now});
  const context=project({context:{tenantId:'t1',missionId:'m1'},operationalFocus:{tenantId:'t1',missionIds:['m1'],at:new Date().toISOString()}},'t1');
  const first=await store.save('t1','s1',context);
  assert.equal(first.saved,true);
  assert.equal(await store.load('t2','s1'),null);
  const restarted=new ConversationContextStore({db,now:()=>now});
  assert.deepEqual((await restarted.load('t1','s1')).context,context);
  const concurrent=await Promise.all([store.save('t1','s1',context,first.revision),restarted.save('t1','s1',context,first.revision)]);
  assert.equal(concurrent.filter(x=>x.saved).length,1);
  assert.equal(concurrent.filter(x=>x.conflict).length,1);
  const revision=(await store.load('t1','s1')).revision;
  now+=7200001;
  assert.equal(await store.load('t1','s1'),null);
  assert.equal((await store.save('t1','s1',context,revision)).conflict,true);
  assert.equal((await store.save('t1','s1',context)).saved,true);
  await store.save('t2','s1',context);
  await store.remove('t1','s1');
  assert.equal(await store.load('t1','s1'),null);
  assert.ok(await store.load('t2','s1'));
  await db.query(`UPDATE max_conversation_context SET context=context || '{"approval":true}'::jsonb WHERE tenant_id='t2'`);
  await assert.rejects(store.load('t2','s1'),/Invalid conversation/);
  now+=7200001;await store.purgeExpired();
  assert.equal((await db.query('SELECT count(*)::integer AS n FROM max_conversation_context')).rows[0].n,0);
});
